#!/usr/bin/env node

/**
 * VOLQ AI Wallpaper Asset Pipeline
 * Generates responsive AVIF, WEBP, and JPEG variants from read-only bg.jpg
 * Outputs to apps/web/public/assets/wallpaper/ and writes wallpaperManifest.ts
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const SOURCE_IMAGE = path.join(ROOT_DIR, 'bg.jpg');
const PUBLIC_WALLPAPER_DIR = path.join(ROOT_DIR, 'apps/web/public/assets/wallpaper');
const MANIFEST_PATH = path.join(ROOT_DIR, 'apps/web/src/assets/wallpaperManifest.ts');

const TARGET_WIDTHS = [640, 960, 1920];
const PLACEHOLDER_WIDTH = 24;

async function generateWallpaperAssets() {
  if (!fs.existsSync(SOURCE_IMAGE)) {
    console.error(`[wallpaper-pipeline] ERROR: Source image not found at ${SOURCE_IMAGE}`);
    process.exit(1);
  }

  const sourceBuffer = fs.readFileSync(SOURCE_IMAGE);
  const sourceHash = crypto.createHash('sha256').update(sourceBuffer).digest('hex');
  const shortHash = sourceHash.slice(0, 8);

  console.log(`[wallpaper-pipeline] Source image: ${SOURCE_IMAGE}`);
  console.log(`[wallpaper-pipeline] Source size: ${(sourceBuffer.length / 1024).toFixed(2)} KB`);
  console.log(`[wallpaper-pipeline] Source SHA256: ${sourceHash}`);

  const metadata = await sharp(sourceBuffer).metadata();
  const originalWidth = metadata.width || 1920;
  const originalHeight = metadata.height || 1280;
  const aspectRatio = originalWidth / originalHeight;

  fs.mkdirSync(PUBLIC_WALLPAPER_DIR, { recursive: true });
  fs.mkdirSync(path.dirname(MANIFEST_PATH), { recursive: true });

  // Generate 24px blurred placeholder
  const placeholderBuffer = await sharp(sourceBuffer)
    .resize(PLACEHOLDER_WIDTH, Math.round(PLACEHOLDER_WIDTH / aspectRatio))
    .blur(2)
    .webp({ quality: 20 })
    .toBuffer();
  const placeholderBase64 = `data:image/webp;base64,${placeholderBuffer.toString('base64')}`;

  const variants = [];
  const avifSrcsetParts = [];
  const webpSrcsetParts = [];
  const jpgSrcsetParts = [];

  for (const width of TARGET_WIDTHS) {
    const height = Math.round(width / aspectRatio);

    const avifFilename = `bg-${width}-${shortHash}.avif`;
    const webpFilename = `bg-${width}-${shortHash}.webp`;
    const jpgFilename = `bg-${width}-${shortHash}.jpg`;

    const avifCanonical = `bg-${width}.avif`;
    const webpCanonical = `bg-${width}.webp`;
    const jpgCanonical = `bg-${width}.jpg`;

    const avifBuffer = await sharp(sourceBuffer)
      .resize(width, height)
      .avif({ quality: 68, effort: 4 })
      .toBuffer();

    const webpBuffer = await sharp(sourceBuffer)
      .resize(width, height)
      .webp({ quality: 78, effort: 4 })
      .toBuffer();

    const jpgBuffer = await sharp(sourceBuffer)
      .resize(width, height)
      .jpeg({ quality: 82, progressive: true })
      .toBuffer();

    fs.writeFileSync(path.join(PUBLIC_WALLPAPER_DIR, avifFilename), avifBuffer);
    fs.writeFileSync(path.join(PUBLIC_WALLPAPER_DIR, webpFilename), webpBuffer);
    fs.writeFileSync(path.join(PUBLIC_WALLPAPER_DIR, jpgFilename), jpgBuffer);

    // Also write canonical names for stable resolution
    fs.writeFileSync(path.join(PUBLIC_WALLPAPER_DIR, avifCanonical), avifBuffer);
    fs.writeFileSync(path.join(PUBLIC_WALLPAPER_DIR, webpCanonical), webpBuffer);
    fs.writeFileSync(path.join(PUBLIC_WALLPAPER_DIR, jpgCanonical), jpgBuffer);

    const avifUrl = `/assets/wallpaper/${avifFilename}`;
    const webpUrl = `/assets/wallpaper/${webpFilename}`;
    const jpgUrl = `/assets/wallpaper/${jpgFilename}`;

    avifSrcsetParts.push(`${avifUrl} ${width}w`);
    webpSrcsetParts.push(`${webpUrl} ${width}w`);
    jpgSrcsetParts.push(`${jpgUrl} ${width}w`);

    variants.push({
      width,
      height,
      avifUrl,
      webpUrl,
      jpgUrl,
      sizeBytes: {
        avif: avifBuffer.length,
        webp: webpBuffer.length,
        jpg: jpgBuffer.length,
      },
    });

    console.log(
      `[wallpaper-pipeline] ${width}x${height} -> AVIF: ${(avifBuffer.length / 1024).toFixed(1)} KB | WEBP: ${(webpBuffer.length / 1024).toFixed(1)} KB | JPG: ${(jpgBuffer.length / 1024).toFixed(1)} KB`
    );
  }

  const sizes = '(max-width: 640px) 640px, (max-width: 1024px) 960px, 1920px';

  const manifestContent = `// Auto-generated by scripts/generate-wallpaper.js - DO NOT EDIT MANUALLY
export interface WallpaperVariant {
  width: number;
  height: number;
  avifUrl: string;
  webpUrl: string;
  jpgUrl: string;
  sizeBytes: {
    avif: number;
    webp: number;
    jpg: number;
  };
}

export interface WallpaperManifest {
  hash: string;
  originalWidth: number;
  originalHeight: number;
  aspectRatio: number;
  focalPointDesktop: string;
  focalPointMobile: string;
  placeholderBase64: string;
  defaultSrc: string;
  sizes: string;
  srcset: {
    avif: string;
    webp: string;
    jpg: string;
  };
  variants: WallpaperVariant[];
}

export const WALLPAPER_MANIFEST: WallpaperManifest = {
  hash: '${shortHash}',
  originalWidth: ${originalWidth},
  originalHeight: ${originalHeight},
  aspectRatio: ${aspectRatio.toFixed(3)},
  focalPointDesktop: '54% 55%',
  focalPointMobile: '54% 30%',
  placeholderBase64: '${placeholderBase64}',
  defaultSrc: '${variants[variants.length - 1].webpUrl}',
  sizes: '${sizes}',
  srcset: {
    avif: '${avifSrcsetParts.join(', ')}',
    webp: '${webpSrcsetParts.join(', ')}',
    jpg: '${jpgSrcsetParts.join(', ')}',
  },
  variants: ${JSON.stringify(variants, null, 2)},
};
`;

  fs.writeFileSync(MANIFEST_PATH, manifestContent, 'utf8');
  console.log(`[wallpaper-pipeline] Wrote manifest to ${MANIFEST_PATH}`);

  // Confirm bg.jpg is bit-for-bit unchanged
  const postBuffer = fs.readFileSync(SOURCE_IMAGE);
  const postHash = crypto.createHash('sha256').update(postBuffer).digest('hex');
  if (postHash !== sourceHash) {
    console.error('[wallpaper-pipeline] FATAL: Source image bg.jpg was modified!');
    process.exit(1);
  }
  console.log('[wallpaper-pipeline] Integrity verified: bg.jpg is identical and unmodified.');
}

generateWallpaperAssets().catch((err) => {
  console.error('[wallpaper-pipeline] Failed:', err);
  process.exit(1);
});
